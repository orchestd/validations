package customValidations

import (
	"github.com/smartystreets/goconvey/convey"
	"testing"
)

func Test_ValidatePhoneNumberAll(t *testing.T) {
	allowedNumbers := []string{
		"0500000000",
		"050-0000000",
		"050 0000000",
		"050.0000000",
		"(050)-0000000",
		"030000000",
		"03-0000000",
		"(03)0000000",
		"03 0000000",
		"050-000-0000",
		"718-444-1122",
		"(718)-444-1122",
		"17184441122",
		"7184441122",
		"1 123-456-7890",
		"1 123 456 7890",
		"18005551234",
		"1 800 555 1234",
		"+1 800 555-1234",
		"(800)555-1234",
		"(800) 555-1234",
		"(800)5551234",
		"800-555-1234",
		"18001234567",
		"1 800 123 4567",
		"+18001234567",
		"+1 800 123 4567",
		"1(800)1234567",
		"+1800 1234567",
		"1.8001234567",
		"18001234567",
		"1 800 123 4567",
		"+1 800 123-4567",
		"(800)123-4567",
		"(800) 123-4567",
		"(800)1234567",
		"800-123-4567",
		"1231231231",
		"123-1231231",
		"123123-1231",
		"123 123-1231",
		"123-123-1231",
		"(123)123-1231",
		"(123) 123-1231",
		"+99 1234567890",
		"+991234567890",
		"(555) 444-6789",
		"555-444-6789",
		"555 444 6789",
		"18005551234",
		"1 800 555 1234",
		"+1 800 555-1234",
		"(800)555-1234",
		"(800) 555-1234",
		"(800)5551234",
		"800-555-1234",
		"(003) 555-1212",
		"(103) 555-1212",
		"(911) 555-1212",
		"18005551234",
		"1 800 555 1234",
	}

	convey.Convey("given allowed phone numbers", t, func() {
		for _, n := range allowedNumbers {
			v := isValidPhoneNumberAll(n)
			convey.So(v, convey.ShouldBeTrue)
		}
	})

	blockedNumbers := []string{
		"xxxxxxxxxx",
		"0500000000000000",
		"050+0000000",
		"050--0000000",
		"(050)(0000000)",
		"[03]0000000",
	}

	convey.Convey("given blocked phone numbers", t, func() {
		for _, n := range blockedNumbers {
			v := isValidPhoneNumberAll(n)
			convey.So(v, convey.ShouldBeFalse)
		}
	})
}
